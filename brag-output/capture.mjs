import { chromium } from './tools/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import path from 'node:path';
const out=path.resolve('brag-output/composition/assets');
const browser=await chromium.launch({executablePath:'C:/Users/HP/.cache/hyperframes/chrome/chrome-headless-shell/win64-152.0.7977.30/chrome-headless-shell-win64/chrome-headless-shell.exe',headless:true,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1500,height:900},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:1500,height:900}}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3000/',{waitUntil:'networkidle',timeout:120000});
await page.screenshot({path:path.join(out,'overview.png')});
