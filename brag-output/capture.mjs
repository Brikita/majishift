await page.locator('.inputs').screenshot({path:path.join(out,'inputs.png')});
await page.locator('.decision').screenshot({path:path.join(out,'decision.png')});
await page.getByLabel('Starting storage',{exact:false}).fill('8000');
await page.getByRole('button',{name:'Compare schedules'}).click();
